// The completion catalog: common LaTeX commands, math symbols, environments and packages. Snippets use CodeMirror's
// syntax (`${1:default}`, `${0}` for the final cursor); entries without a field are inserted as written.

export interface CatalogItem {
  label: string;
  insertText: string;
  detail?: string;
  package?: string;
}

type Row = [label: string, insertText: string, detail: string, pkg?: string];

const rows = (list: Row[]): CatalogItem[] =>
  list.map(([label, insertText, detail, pkg]) => ({ label, insertText, detail, ...(pkg ? { package: pkg } : {}) }));

/** "alpha α" → `\alpha` with the glyph as its description. */
const symbols = (pkg: string | undefined, ...entries: string[]): CatalogItem[] =>
  entries.map((entry) => {
    const [name, ...glyph] = entry.split(" ");
    return { label: `\\${name}`, insertText: `\\${name}`, detail: glyph.join(" "), ...(pkg ? { package: pkg } : {}) };
  });

